import mongoose from "mongoose";

const projectSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: [true, "Project name is required"],
      trim: true,
      minlength: [3, "Project name must be at least 3 characters"],
      maxlength: [80, "Project name cannot exceed 80 characters"],
    },
    description: {
      type: String,
      trim: true,
      maxlength: [500, "Description cannot exceed 500 characters"],
      default: "",
    },
    owner: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },
    // Owner is NOT in this list. Members are the invited collaborators.
    members: [{ type: mongoose.Schema.Types.ObjectId, ref: "User" }],

    // README shown on the public page (generated by Gemini or written by the owner)
    readme: { type: String, default: "", maxlength: 50000 },

    // Public sharing
    isPublic: { type: Boolean, default: false },
    shareToken: { type: String, unique: true, sparse: true }, // sparse = many projects may have no token
  },
  { timestamps: true }
);

// Fast lookup for "projects where I am a member"
projectSchema.index({ members: 1 });

export default mongoose.model("Project", projectSchema);